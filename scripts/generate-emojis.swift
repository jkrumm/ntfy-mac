#!/usr/bin/env swift  // Fetches the gemoji database (the source ntfy uses) and generates
// Sources/NtfyCore/TagEmojiData.swift. Run: swift scripts/generate-emojis.swift
import Foundation

let sourceURL = "https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json"
let outputURL = URL(fileURLWithPath: #filePath)
  .deletingLastPathComponent().deletingLastPathComponent()
  .appendingPathComponent("Sources/NtfyCore/TagEmojiData.swift")

func fail(_ message: String) -> Never {
  FileHandle.standardError.write(Data("generate-emojis: \(message)\n".utf8))
  exit(1)
}

guard let url = URL(string: sourceURL), let data = try? Data(contentsOf: url) else {
  fail("cannot fetch \(sourceURL)")
}
guard let entries = try? JSONSerialization.jsonObject(with: data) as? [[String: Any]] else {
  fail("unexpected gemoji JSON shape")
}

var lines: [String] = []
for entry in entries {
  guard let emoji = entry["emoji"] as? String, let aliases = entry["aliases"] as? [String] else {
    continue
  }
  for alias in aliases where !alias.isEmpty {
    lines.append("\(alias) \(emoji)")
  }
}
guard !lines.isEmpty else { fail("no entries found") }

let body = lines.map { "    \($0)" }.joined(separator: "\n")
let output = """
  // Auto-generated by scripts/generate-emojis.swift. Do not edit manually.
  // Source: https://github.com/github/gemoji/blob/master/db/emoji.json
  // Regenerate with: swift scripts/generate-emojis.swift

  /// One `alias emoji` pair per line; `TagEmoji` parses it once.
  enum TagEmojiData {
    static let lines = \"\"\"
  \(body)
      \"\"\"
  }

  """
do {
  try output.write(to: outputURL, atomically: true, encoding: .utf8)
} catch {
  fail("cannot write \(outputURL.path): \(error)")
}
print("Written \(lines.count) entries to \(outputURL.path)")
